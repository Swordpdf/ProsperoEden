#!/usr/bin/env python3
"""Generate JSON adapters for the launcher service models."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2] / 'headless/prosperoeden/pe/ui'
text = (root / 'services.hpp').read_text(encoding='utf-8')
text = re.sub(r'//[^\n]*', '', text)
types = ['Game','SourceInfo','Sources','SaveSync','SaveSyncProfile','SaveSyncSetup','PairServer',
         'PairingStatus','Download','Recent','Home','Profile','Preferences','GameSettings','Cheat','Mod','GameCheat',
         'FolderInfo','UpdateOffer','UpdateStatus']
lines = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// API model serialization; generated by tools/launcher/generate-runtime-models.py.',
         '#pragma once', '#include <nlohmann/json.hpp>', '#include "pe/ui/services.hpp"', 'namespace pe::ui {']
for name in types:
    block = re.search(r'\bstruct '+name+r'\s*\{(.*?)\n\};',text,re.S).group(1)
    fields = re.findall(r'^\s*(?:[\w:]+(?:<[^;\n=]+>)?(?:\s*&)?\s+)(\w+)\s*(?:[;={])',block,re.M)
    assert fields, name
    # from_json defaults preserve missing optional fields across minor API additions.
    lines.append('NLOHMANN_DEFINE_TYPE_NON_INTRUSIVE_WITH_DEFAULT('+name+', '+', '.join(fields)+')')
lines.append('}')
(root / 'runtime_models.hpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
